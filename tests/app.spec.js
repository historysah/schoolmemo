import {test,expect} from '@playwright/test';
test('학생 등록과 수정, 다중 연결, 검색, 별표, 저장, 삭제',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');
 await page.getByRole('button',{name:/학생 명부 및 인적사항/}).click();
 await page.getByRole('button',{name:'학생 추가'}).click();
 let d=page.locator('dialog');
 await d.getByLabel('이름 *').fill('테스트학생');
 await d.getByLabel('학년 *').fill('1');await d.getByLabel('반 *',{exact:true}).fill('2');await d.getByLabel('번호 *',{exact:true}).fill('5');
 await d.getByRole('button',{name:'저장하기'}).click();
 await page.getByRole('button',{name:/테스트학생/}).click();
 await page.getByRole('button',{name:'기본 정보 수정'}).click();
 await d.getByLabel('보호자 1 관계').selectOption('모');await d.getByLabel('보호자 1 성함').fill('테스트보호자');await d.getByRole('button',{name:'저장하기'}).click();
 await expect(page.getByText('테스트보호자',{exact:true})).toBeVisible();
 await page.locator('#add').click();
 await d.getByLabel('제목 *').fill('함께한 상담');await d.getByLabel('내용 *').fill('이야기 @김');
 await d.getByRole('button',{name:'김하늘 2학년 3반 1번'}).click();
 await expect(d.getByRole('button',{name:'테스트학생 연결 해제'})).toBeVisible();
 await d.getByRole('button',{name:'저장하기'}).click();
 await page.reload();d=page.locator('#inline-editor');await page.getByRole('button',{name:'함께한 상담',exact:true}).click();
 await expect(d.getByRole('button',{name:'김하늘 연결 해제'})).toBeVisible();
 await d.getByRole('button',{name:'김하늘 연결 해제'}).click();
 await d.getByLabel('★ 중요 기록으로 표시').check();await d.getByRole('button',{name:'저장하기'}).click();
 await page.getByLabel('기록 검색',{exact:true}).fill('테스트학생');
 await page.getByLabel(/중요 기록만 보기/).check();
 await expect(page.getByRole('button',{name:'함께한 상담',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'함께한 상담',exact:true}).click();
 page.once('dialog',d=>d.dismiss());await page.getByRole('button',{name:'기록 삭제',exact:true}).click();await expect(d).toBeVisible();
 page.once('dialog',d=>d.accept());await page.getByRole('button',{name:'기록 삭제',exact:true}).click();
 await expect(page.getByRole('button',{name:'함께한 상담',exact:true})).toHaveCount(0);
 expect(errors).toEqual([]);
});
test('학생 없는 기록과 학생별 중요 필터, 모바일 화면',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await page.locator('#add').click();
 await page.getByLabel('제목 *').fill('<새 회의>');await page.getByLabel('내용 *').fill('학생 연결 없이 회의 기록');await page.getByRole('button',{name:'저장하기'}).click();
 await expect(page.getByRole('button',{name:'<새 회의>',exact:true})).toBeVisible();
 await page.getByRole('button',{name:/학생 명부 및 인적사항/}).click();await page.getByLabel('학생 이름 검색').fill('하늘');await page.getByRole('button',{name:/김하늘/}).click();
 await page.getByLabel(/중요 기록만 보기/).check();await expect(page.getByRole('button',{name:'새 학기 적응 이야기',exact:true})).toBeVisible();
 await page.getByRole('button',{name:'새 학기 적응 이야기 중요 표시'}).click();await expect(page.getByText('아직 표시할 기록이 없어요.',{exact:false})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/schoolmemo-mobile.png',fullPage:true});
});
test('작성 중 검색과 별표 변경에도 초안 유지, 기록 수정 및 배치',async({page})=>{
 await page.setViewportSize({width:1600,height:1000});await page.goto('/');
 const editor=page.locator('#inline-editor');
 await editor.getByLabel('제목 *').fill('작성 중 초안');await editor.getByLabel('내용 *').fill('초안 내용');
 await page.getByLabel('기록 검색',{exact:true}).fill('하늘');
 await expect(editor.getByLabel('제목 *')).toHaveValue('작성 중 초안');
 await page.getByRole('button',{name:'새 학기 적응 이야기 중요 표시'}).click();
 await expect(editor.getByLabel('내용 *')).toHaveValue('초안 내용');
 await editor.getByRole('button',{name:'저장하기'}).click();
 await page.getByLabel('기록 검색',{exact:true}).fill('');
 await page.getByRole('button',{name:'작성 중 초안',exact:true}).click();
 await editor.getByLabel('제목 *').fill('수정 완료');
 await page.getByLabel('기록 검색',{exact:true}).fill('초안');
 await expect(editor.getByLabel('제목 *')).toHaveValue('수정 완료');
 await editor.getByRole('button',{name:'저장하기'}).click();
 await page.getByLabel('기록 검색',{exact:true}).fill('');
 await page.reload();
 await expect(page.getByRole('button',{name:'수정 완료',exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'작성 중 초안',exact:true})).toHaveCount(0);
 const archiveBox=await page.locator('.archive').boundingBox();const editorBox=await editor.boundingBox();expect(editorBox.x).toBeGreaterThan(archiveBox.x+archiveBox.width);
 await page.screenshot({path:'/tmp/schoolmemo-stitch-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'/tmp/schoolmemo-stitch-mobile.png',fullPage:true});
});
